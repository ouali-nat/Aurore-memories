"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

function element() {
  return {
    textContent: "", innerHTML: "", value: "", hidden: false, disabled: false,
    dataset: {}, parentNode: { insertBefore() {} },
    classList: { toggle() {} },
    setAttribute() {}, addEventListener() {}, appendChild() {}, append() {},
    replaceChildren() {}, focus() {}
  };
}
const elements = {};
["#qcmForm", "#qcmQuestionEditor", "#bulkQcmImportText", "#bulkQcmImportStatus",
 "#bulkQcmImportPreview", "#bulkQcmImportList", "#bulkQcmAnalyze", "#bulkQcmTransfer",
 "#bulkQcmCancel", "#bulkQcmImportCount"].forEach((key) => { elements[key] = element(); });
elements["#qcmForm"].parentNode = { insertBefore() {} };
const document = {
  head: { appendChild() {} },
  createElement() { return element(); },
  querySelector(selector) { return elements[selector] || null; },
  dispatchEvent() {},
  addEventListener() {}
};
const window = {};
vm.runInNewContext(fs.readFileSync("qcm-text-import.js", "utf8"), {
  document, window, console, CustomEvent: function CustomEvent() {}
});
const parser = window.AuroreQcmTextImportParser;
assert.ok(parser, "parser API is exposed for deterministic regression tests");

const text = [
  "Question 1 : Quelle est la dérivée de f(x)=x² ?",
  "A) 2x",
  "B) x",
  "C) x²",
  "D) 2",
  "Bonne réponse : A",
  "Explication : La dérivée de x² est 2x.",
  "",
  "Question 2",
  "Quelle est la valeur de 2+2 ?",
  "A. 3",
  "B. 4",
  "C. 5",
  "D. 6",
  "Réponse correcte : B",
  "Justification : 2+2=4."
].join("\n");
const parsed = parser.parseText(text);
assert.equal(parsed.found, 2, "recognizes numbered and unpunctuated question headings");
assert.deepEqual(Array.from(parsed.errors), [], "complete questions with answer keys are importable");
assert.equal(parsed.questions[0].correctIndex, 0);
assert.equal(parsed.questions[1].correctIndex, 1);
assert.match(parsed.questions[0].prompt, /Quelle est la dérivée/);
assert.match(parsed.questions[1].prompt, /Quelle est la valeur/);

const alternate = parser.parseText([
  "QCM 1",
  "Question : Résoudre \(x+1=3\).",
  "A) x=1",
  "B) x=2",
  "C) x=3",
  "D) x=4",
  "**Bonne réponse : B**",
  "Explication : On soustrait 1 des deux côtés."
].join("\n"));
assert.equal(alternate.found, 1, "accepts QCM headings followed by a separate Question label");
assert.deepEqual(Array.from(alternate.errors), [], "recognizes bold answer labels");
assert.equal(alternate.questions[0].correctIndex, 1);

const missing = parser.parseText([
  "Question 1: Choisir la bonne réponse",
  "A) un",
  "B) deux"
].join("\n"));
assert.ok(missing.errors.some((error) => /bonne réponse absente/.test(error)),
  "rejects questions without a recognized correct answer");

const json = parser.parseText(JSON.stringify({
  action: { type: "create_qcm", questions: [{
    prompt: "Calculer \\(f'(x)\\).",
    options: ["\\(2x\\)", "\\(x\\)", "\\(x^2\\)", "\\(2\\)"],
    correctIndex: 0,
    explanation: "La dérivée est \\(2x\\)."
  }] }
}));
assert.equal(json.found, 1, "accepts structured JSON generated by an AI");
assert.deepEqual(Array.from(json.errors), []);
assert.match(parser.normalizeMath("f(x)=x^2"), /^\\\(/, "wraps a bare mathematical expression");
assert.equal(parser.normalizeMath("Calculer f(x)=x^2"), "Calculer f(x)=x^2",
  "does not wrap French prose in math mode");
console.log("QCM text import tests passed (5 scenarios).");